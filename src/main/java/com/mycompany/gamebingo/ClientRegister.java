    public boolean find(String name){
        String path = name.replace(" ", "_");
        path = path+".txt";
        File file = new File(getPath(path));
        if(file.exists()){
            try{
                InputStream input_file = new FileInputStream(file);
                InputStreamReader doc = new InputStreamReader(input_file);
                BufferedReader read = new BufferedReader(doc);
                diemSo = Long.parseLong(read.readLine());
                doc.close();
                return true;
            }catch(IOException e){
                return false;
            }
        }
        else{
            return false;
        }
    }

    
    private void btn_connectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_connectActionPerformed

        if (btnavata1.isSelected())
        {
            hinhnen = "mot";
        }
        else if (btnavata2.isSelected())
        {
            hinhnen = "hai";
        }
        else if (btnavata3.isSelected())
        {
            hinhnen = "ba";
        }
        else
        {
            hinhnen = "bon";
        }
        try
        {
            String id = txt_id.getText();
            if (!id.equals("")){
                //lấy dữ liệu được nhập từ txt_id gán vào biến id
                Socket sk = new Socket("localhost",8080); // tạo kết nối đến máy chủ tại port 8080
                DataInputStream datain = new DataInputStream(sk.getInputStream()); // biến datain dùng để nhận dữ liệu từ server thông qua biến sk
                DataOutputStream dataout = new DataOutputStream(sk.getOutputStream()); // biến dataout dùng để gửi dữ liệu lên server thông qua biến sk
                dataout.writeUTF(id); //giá trị cảu biến id sẽ được lưu vào luồng đầu ra thông qua biến dataout
                String i = new DataInputStream(sk.getInputStream()).readUTF(); //biến i dùng để lưu dữ liệu phản hồi từ server
                if (i.equals("YOU ALREADY REGISTERED!!")) // nếu ID đã tồn tại thì hiển thị thông báo
                {
                    JOptionPane.showMessageDialog(this,"ID da ton tai \n");
                }
                else // nếu tên ID chưa tồn tại thì chạy Jframe ClientBingo1 và giải phóng JFrame hiện tại (ClientRegister)
                {
                    if(!find(id)){
                        diemSo = 50;
                    }
                    new ClientBingo1(id,sk,hinhnen,diemSo).setVisible(true);
                    this.dispose();
                }
            }
            else{
                JOptionPane.showMessageDialog(this,"Bạn chưa nhập ID","ERROR",JOptionPane.ERROR_MESSAGE);
            }
        }
        catch (IOException ex)
        {
            System.out.print("loi id dang nhap");
        }
        // TODO add your handling code here:
    }//GEN-LAST:event_btn_connectActionPerformed

